/** The pure-Kotlin QR encoder against matrices produced by an independent encoder (segno). */
class TvQrCodeTest {
    @Test fun activateUrlMatchesReferenceAtVersion3() {
        val qr = TvQrCode.encode("https://www.youtube.com/activate", mask = 2)!!
        assertEquals(3, qr.version)
        assertEquals(ACTIVATE, qr.rows())
    }

    @Test fun longUrlUsesVersion7WithVersionBlocks() {
        val qr = TvQrCode.encode("https://github.com/nev-minhnh/MinTube/" + "abcdefghij".repeat(7) + "xyz", mask = 5)!!
        assertEquals(7, qr.version)
        assertEquals(LONG, qr.rows())
    }

    @Test fun shortTextFitsVersion1() {
        val qr = TvQrCode.encode("HELLO", mask = 0)!!
        assertEquals(21, qr.size)
        assertEquals(HELLO, qr.rows())
    }

    @Test fun automaticMaskKeepsTheSameDataAsTheForcedMask() {
        val auto = TvQrCode.encode("https://www.youtube.com/activate")!!
        assertTrue(auto.mask in 0..7)
        assertEquals(TvQrCode.encode("https://www.youtube.com/activate", mask = auto.mask)!!.rows(), auto.rows())
    }

    @Test fun capacityLimits() {
        assertEquals(14, TvQrCode.byteCapacity(1))
        assertEquals(213, TvQrCode.byteCapacity(10))
        assertNotNull(TvQrCode.encode("a".repeat(213)))
        assertNull(TvQrCode.encode("a".repeat(214)))
    }

